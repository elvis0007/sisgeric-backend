-- Migración V9: Agregar estado ADICIONAL en el catálogo de estados de verificables (AI_REC_ESTADO_VERIFICABLE)
-- Regla de negocio: Este estado SOLO aplica y se clasifica por defecto cuando el verificable es subido
-- con posterioridad a que la recomendación fue cambiada al estado CUMPLIDA.
-- Los verificables originales que sustentaron y justificaron el cumplimiento de la recomendación se mantienen intactos como JUSTIFICA.
MERGE INTO ROOTSISREC.AI_REC_ESTADO_VERIFICABLE TARGET
USING (SELECT 4 AS AREEV_CODIGO, 'ADICIONAL' AS AREEV_DESCRIPCION, '#0ea5e9' AS AREEV_COLOR, 'ROOTSISREC' AS AREEV_USUARIO, SYSDATE AS AREEV_FECHA, '1' AS AREEV_ESTADO FROM DUAL) SOURCE
ON (TARGET.AREEV_CODIGO = SOURCE.AREEV_CODIGO)
WHEN MATCHED THEN
  UPDATE SET TARGET.AREEV_DESCRIPCION = SOURCE.AREEV_DESCRIPCION, TARGET.AREEV_ESTADO = SOURCE.AREEV_ESTADO
WHEN NOT MATCHED THEN
  INSERT (AREEV_CODIGO, AREEV_DESCRIPCION, AREEV_COLOR, AREEV_USUARIO, AREEV_FECHA, AREEV_ESTADO)
  VALUES (SOURCE.AREEV_CODIGO, SOURCE.AREEV_DESCRIPCION, SOURCE.AREEV_COLOR, SOURCE.AREEV_USUARIO, SOURCE.AREEV_FECHA, SOURCE.AREEV_ESTADO);

COMMIT;
