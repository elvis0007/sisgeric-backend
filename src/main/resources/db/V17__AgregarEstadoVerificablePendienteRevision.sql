-- Migración V17: Agregar estado PENDIENTE DE REVISIÓN en el catálogo de estados de verificables (AI_REC_ESTADO_VERIFICABLE)
-- Regla de negocio: Por defecto, al subir un verificable el responsable, este se crea con estado 'PENDIENTE DE REVISIÓN' (código 5).
-- El estado 'PENDIENTE' (código 1) queda reservado para cuando la auditora evalúa y lo deja en estado PENDIENTE.
MERGE INTO ROOTSISREC.AI_REC_ESTADO_VERIFICABLE TARGET
USING (SELECT 5 AS AREEV_CODIGO, 'PENDIENTE DE REVISIÓN' AS AREEV_DESCRIPCION, '#f59e0b' AS AREEV_COLOR, 'ROOTSISREC' AS AREEV_USUARIO, SYSDATE AS AREEV_FECHA, '1' AS AREEV_ESTADO FROM DUAL) SOURCE
ON (TARGET.AREEV_CODIGO = SOURCE.AREEV_CODIGO)
WHEN MATCHED THEN
  UPDATE SET TARGET.AREEV_DESCRIPCION = SOURCE.AREEV_DESCRIPCION, TARGET.AREEV_COLOR = SOURCE.AREEV_COLOR, TARGET.AREEV_ESTADO = SOURCE.AREEV_ESTADO
WHEN NOT MATCHED THEN
  INSERT (AREEV_CODIGO, AREEV_DESCRIPCION, AREEV_COLOR, AREEV_USUARIO, AREEV_FECHA, AREEV_ESTADO)
  VALUES (SOURCE.AREEV_CODIGO, SOURCE.AREEV_DESCRIPCION, SOURCE.AREEV_COLOR, SOURCE.AREEV_USUARIO, SOURCE.AREEV_FECHA, SOURCE.AREEV_ESTADO);

COMMIT;
